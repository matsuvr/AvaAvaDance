        internal sealed class Entry
        {
            internal readonly Command Id;
            internal readonly string Japanese, English;
            internal readonly Entry[] Children;
            internal Entry(Command id, string japanese, string english, params Entry[] children)
            { Id = id; Japanese = japanese; English = english; Children = children; }
            internal string Raw(bool english) => english ? English : Japanese;
            internal string Label(bool english) => Raw(english).Replace("(&", "(");
            internal char Access(bool english)
            {
                string raw = Raw(english);
                int i = raw.IndexOf("(&", StringComparison.Ordinal);
                return i >= 0 ? char.ToLowerInvariant(raw[i + 2]) : '\0';
            }
        }

